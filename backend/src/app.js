import express from 'express';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { env } from './config/environment.js';
import authRoutes from './routes/auth.routes.js';
import serviceRoutes from './routes/services.routes.js';
import barberRoutes from './routes/barbers.routes.js';
import bookingRoutes from './routes/bookings.routes.js';
import paymentRoutes from './routes/payments.routes.js';
import mediaRoutes from './routes/media.routes.js';
import reviewRoutes from './routes/reviews.routes.js';
import settingsRoutes from './routes/settings.routes.js';
import adminRoutes from './routes/admin.routes.js';
import { notFound,errorHandler } from './middleware/error-handler.js';
const app=express();
const here=path.dirname(fileURLToPath(import.meta.url));
const projectRoot=path.resolve(here,'../../');
app.use(helmet({contentSecurityPolicy:false}));
app.use(express.json({limit:'1mb'}));
app.use(express.urlencoded({extended:false,limit:'1mb'}));
app.use(cookieParser());
app.get('/api/health',(req,res)=>res.json({ok:true,service:'cherish-barbershop-api'}));
app.use('/api/auth',authRoutes);
app.use('/api/services',serviceRoutes);
app.use('/api/barbers',barberRoutes);
app.use('/api/bookings',bookingRoutes);
app.use('/api/payments',paymentRoutes);
app.use('/api/media',mediaRoutes);
app.use('/api/reviews',reviewRoutes);
app.use('/api/settings',settingsRoutes);
app.use('/api/admin',adminRoutes);
app.use('/uploads',express.static(path.resolve(env.uploadDir),{index:false, dotfiles:'deny', maxAge:env.nodeEnv==='production'?'1d':0}));
app.use(express.static(path.join(projectRoot,'frontend')));
app.use(notFound);
app.use(errorHandler);
export default app;
